def tr(key, *args):
    text = T.get(CURRENT_LANG, T["pl"]).get(key, key)
    if args:
        try:
            return text.format(*args)
        except Exception:
            pass
    return text


def rev_tr(translated_text, key_list):
    for k in key_list:
        if tr(k) == translated_text:
            return k
    return key_list[0] if key_list else translated_text